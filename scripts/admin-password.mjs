#!/usr/bin/env node
/**
 * Make a password hash for the admin portal.
 *
 *   node scripts/admin-password.mjs                  random password: prints it and its hash
 *   node scripts/admin-password.mjs "a passphrase"   hashes the one you give
 *   ... --write-starter [--username ryan]            also rewrites netlify/admin-bootstrap.mjs
 *
 * Normal password changes happen in the portal (Account). This is for the
 * two cases the portal can't cover:
 *   - Locked out / forgot the password: run it, then in Netlify set
 *     ADMIN_PASSWORD_HASH to the printed hash (and ADMIN_USERNAME if wanted)
 *     and redeploy. That variable overrides everything else until deleted.
 *   - Replacing the starter credential in the repo (--write-starter).
 */
import crypto from "node:crypto";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { hashPassword } from "../netlify/password-hash.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const flag = (name) => args.includes(name);
const option = (name) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
};

// No look-alike characters (0/o, 1/l/i), so it can be read aloud or retyped.
const ALPHABET = "abcdefghjkmnpqrstuvwxyz23456789";
function randomPassword() {
  const group = () => Array.from({ length: 5 }, () => ALPHABET[crypto.randomInt(ALPHABET.length)]).join("");
  return [group(), group(), group(), group()].join("-");
}

const username = (option("--username") ?? "ryan").trim().toLowerCase();
const given = args.find((arg, i) => !arg.startsWith("--") && args[i - 1] !== "--username");
const password = given ?? randomPassword();
const hash = await hashPassword(password);

if (flag("--write-starter")) {
  const file = path.join(ROOT, "netlify", "admin-bootstrap.mjs");
  await fs.writeFile(
    file,
    `/**
 * Starter admin credential — generated by scripts/admin-password.mjs.
 *
 * Only a scrypt hash is stored here, never the password. It is used until a
 * password is saved from the portal's Account dialog, and ignored from then
 * on. See netlify/admin-core.mjs for the full order of precedence.
 */
export const BOOTSTRAP_CREDENTIAL = {
  username: ${JSON.stringify(username)},
  hash: ${JSON.stringify(hash)},
};
`
  );
  console.log(`Wrote ${path.relative(ROOT, file)}`);
}

console.log(`username: ${username}`);
if (!given) console.log(`password: ${password}`);
console.log(`hash:     ${hash}`);
